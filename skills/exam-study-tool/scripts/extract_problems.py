"""Extract assigned end-of-chapter problems + their answers from a textbook PDF into book.js.

Copy next to the course's study-tool folder, fill in CONFIG, run `python extract_problems.py`.
Requires pymupdf. Only works on a text PDF: if get_text() returns garbage the scan is image-only
(no OCR here — fall back to page references instead of problem text).

Order of work (do not skip the survey):
  1. d.get_toc() → section and PROBLEMS page ranges. If the TOC is empty, grep for section headings.
  2. Find the printed-page offset: printed = pdf_page - OFF. Verify on 2-3 pages; it can differ per chapter.
  3. Fill CONFIG, run, then READ THE PRINTED OUTPUT and hand-fix anything mangled via FIX.
"""
import json, re, pymupdf

# ---------------- CONFIG ----------------
PDF = '../textbook.pdf'
OUT = 'book.js'
OFF = 33                                            # printed page = 1-based pdf page - OFF
PROB = {1: (68, 72), 2: (117, 124)}                 # chapter -> (first, last) 1-based pdf pages of its PROBLEMS section
ANS = (1180, 1184)                                  # 1-based pdf page range of the answers appendix for those chapters
WANT = {1: [17, 22, 24], 2: [42, 46]}               # chapter -> assigned problem numbers (from the objectives sheet)
FIG = set()                                         # ids whose problem needs a figure ('3.79') — flagged in the UI
FIX = {}                                            # id -> hand-corrected answer HTML, for ones the parser mangles
JUNK = re.compile(r'Chapter \d+ • Problems\s*\d*|ISTUDY|Concept Review Questions|Skill-Building Exercises[^\n]*|Problems in Context|Comprehensive Problems')
# ----------------------------------------

d = pymupdf.open(PDF)
# an answer marker is followed by "(" or a non-lowercase word; "1.34 m" and "4.40 g" are values, not markers
mark = lambda ch: re.compile(r'(?<![\d.\w])' + str(ch) + r'\.(\d{1,3})(?=\(|\s+[^a-z\s])')


def problems(ch):
    """{number: (pdf_page, text)}. Found by line-start markers, so two-column order does not matter."""
    first = {}
    for p in range(PROB[ch][0], PROB[ch][1] + 1):
        t = JUNK.sub('', d[p - 1].get_text())
        ms = list(re.finditer(r'(?m)^\s*' + str(ch) + r'\.(\d{1,3})(?=\s|\(|$)', t))
        for k, m in enumerate(ms):
            end = ms[k + 1].start() if k + 1 < len(ms) else len(t)
            first.setdefault(int(m.group(1)), (p, t[m.end():end]))
    return first


atext = re.sub(r'ISTUDY|A-\d+|Appendix [A-E] • Answers to Selected Problems', '',
               '\n'.join(d[p - 1].get_text() for p in range(ANS[0], ANS[1] + 1)))


def answer(ch, n):
    """Answers run inline, so slice from this number's marker to the next nearby one."""
    ms = [m for m in re.finditer(r'(?<![\d.\w])' + str(ch) + r'\.' + str(n) + r'(?=[\s(])', atext)
          if not atext[m.end():m.end() + 3].startswith(' g')]
    if not ms: return ''
    m = ms[0]
    nxt = [x for x in mark(ch).finditer(atext, m.end()) if n < int(x.group(1)) <= n + 10]
    return atext[m.end():nxt[0].start() if nxt else len(atext)]


def html(s):
    """Plain PDF text -> HTML sub/superscripts. Charges are stashed first so the subscript rule cannot eat them."""
    s = ' '.join(re.sub(r'[­​]', '', s).split())
    s = re.sub(r'(\w)- (\w)', r'\1\2', s)                                    # "den- sity" line-break hyphens
    s = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    s = re.sub(r'\s*PROBLEMS$', '', s)
    s = re.sub(r'×10(−?\d+)', r'×10<sup>\1</sup>', s)
    s = re.sub(r'\b(cm|mm|dm|km|m|in|ft|mi)([23])\b', r'\1<sup>\2</sup>', s)
    ch = []
    keep = lambda x: (ch.append(x), f'\x00{len(ch) - 1}\x00')[1]
    s = re.sub(r'([A-Z][a-z]?|\))(\d+) (\d?−|\d?\+(?=\())', lambda m: m.group(1) + m.group(2) + keep(m.group(3)), s)  # "SO4 2−", "NH4 +(aq)"
    s = re.sub(r'(?<![A-Za-z)])([A-Z][a-z]?)(\d?[+−])(?!\w)', lambda m: m.group(1) + keep(m.group(2)), s)             # "Al3+", "2K+(aq)"
    s = re.sub(r'(OH|CN)([+−])', lambda m: m.group(1) + keep(m.group(2)), s)
    s = re.sub(r'(\([^()]* [^()]*\))(\d)', r'\1<sup>\2</sup>', s)                                                     # "(2.54 cm)2" squared unit
    s = re.sub(r'([A-Z][a-z]?|\))(\d+)', r'\1<sub>\2</sub>', s)
    return re.sub('\x00(\\d+)\x00', lambda m: f'<sup>{ch[int(m.group(1))]}</sup>', s)


out = []
for ch, nums in WANT.items():
    probs = problems(ch)
    for n in nums:
        i = f'{ch}.{n}'
        p, q = probs[n]
        a = FIX.get(i) or answer(ch, n)
        assert q.strip() and a.strip(), f'{i}: empty (check PROB/ANS ranges, or add it to FIX)'
        out.append({'id': i, 'ch': ch, 'page': p - OFF, 'fig': i in FIG, 'q': html(q), 'a': a if i in FIX else html(a)})

open(OUT, 'w', encoding='utf8').write(
    '// Generated by extract_problems.py — assigned end-of-chapter problems + answers.\n'
    '(typeof window !== "undefined" ? window : globalThis).BOOKQ = ' + json.dumps(out, ensure_ascii=False) +
    ';\nif (typeof module !== "undefined") module.exports = globalThis.BOOKQ;\n')
print(len(out), 'problems ->', OUT)
for o in out:  # ALWAYS eyeball this: spills from column breaks and mangled formulas show up here
    print(f"{o['id']:6} p{o['page']:<5} q{len(o['q']):4} a{len(o['a']):4} | {o['a'][:70]}")
